#!/usr/bin/env python3
"""Builds the clean (leak-free) evaluation corpus for logSguarDian.

Replaces attack-sim/large_corpus_requests.json, which was previously
committed with NO generator script and traced back to a corpus whose cmdi
branch collapsed onto the SecLists command-injection-commix.txt file also
used in training (see docs/config3b-results.md, "Ronda 4 (con fuga,
histórico)" section, and the new declaration section this branch adds
above it).

Sources per category (Table 14 of the protocol):
  - sqli            : sqlmap traffic logs against GET /posts/search?q= and
                       POST /login (attack-sim/sqlmap_out/traffic_*.txt),
                       generated by running sqlmap against the live app
                       first (see README at the bottom of this file / task
                       report for the exact sqlmap invocations used).
  - path_traversal  : own generator, attack-sim/generators/path_traversal_gen.py
  - cmdi            : own generator, attack-sim/generators/cmdi_gen.py -
                       deliberately NOT derived from SecLists.
  - xss             : Real OWASP ZAP Active Scan, run via ZAP's REST API
                       (2026-10-10) against POST /posts (content/title) and
                       POST /profile (bio), authenticated as alice through
                       a ZAP context/user set up over the same API - no
                       manual browser/proxy steps in the end. One confirmed
                       vulnerable parameter (`bio`); `content`/`title` came
                       back clean. See attack-sim/zap-evidence/ for the raw
                       report and full alert export. The `xss_placeholder_`
                       id prefix is kept for backward compatibility with
                       existing tooling/docs that reference it - it no
                       longer means "placeholder data," just "the xss
                       category's entries."

Every candidate (all categories) is cross-checked against the training
corpus via attack-sim/exclusion_filter.py before being kept - exact-hash
match on payload text, plus (cmdi only) template-shape match against the
SecLists source. Matches are discarded, not flagged. Full accounting is
written to attack-sim/exclusion_report.json.

Reproducibility: SEED below is fixed and documented. Every source of
randomness in this file and in attack-sim/generators/*.py is seeded from
it (no bare `random.random()`/`random.choice()` calls, no dict/set
iteration order dependency - candidate lists are deduplicated while
preserving first-seen order, never via unordered set iteration). Running
this script twice against the same inputs (training corpus + sqlmap
traffic logs) produces byte-identical output; verified as part of this
change (see task report).
"""
from __future__ import annotations

import json
import random
import sys
from collections import Counter
from pathlib import Path

ATTACK_SIM_DIR = Path(__file__).parent
sys.path.insert(0, str(ATTACK_SIM_DIR))
sys.path.insert(0, str(ATTACK_SIM_DIR / "generators"))

import exclusion_filter as ef  # noqa: E402
import cmdi_gen  # noqa: E402
import path_traversal_gen  # noqa: E402
import sqlmap_extract  # noqa: E402

SEED = 20260923  # today's date (2026-09-23) at authoring time - fixed, documented.

OUTPUT_PATH = ATTACK_SIM_DIR / "large_corpus_requests.json"
BACKUP_PATH = ATTACK_SIM_DIR / "large_corpus_requests.json.leaked.bak"
REPORT_PATH = ATTACK_SIM_DIR / "exclusion_report.json"
SQLMAP_OUT_DIR = ATTACK_SIM_DIR / "sqlmap_out"

TARGET_COUNTS = {
    "sqli_search": 100,
    "sqli_login": 100,
    "path_traversal": 200,
    "cmdi": 200,
}

# Real OWASP ZAP active-scan export (2026-10-10, via ZAP's REST API -
# attack-sim/zap-evidence/zap-xss-report.json, zap-alerts-full.json).
# NOT the hand-picked placeholder list this replaced.
#
# n=1, not n=15 like the old placeholder list, and that is not an oversight:
# ZAP's Active Scan reports one alert per confirmed-vulnerable
# parameter+technique, carrying the payload that actually triggered it - it
# does not enumerate every payload it tried. The scan covered both candidate
# sinks (POST /posts `content`/`title`, POST /profile `bio`); only `bio`
# came back vulnerable (High risk, Medium confidence, Reflected XSS rule -
# functionally persistent/stored since `bio` is saved to the DB and
# re-rendered on every profile view, see src/routes/profile.js:20-24,
# but ZAP's generic rule name doesn't distinguish that). `content`/`title`
# were tested and came back clean (properly escaped) - not vulnerable to
# the payloads ZAP tried, so nothing to add from that sink.
#
# Padding this list with extra hand-picked variants to match the other
# categories' n=200 would misrepresent what was actually confirmed
# exploitable against this app. The small n is the honest result, not a
# placeholder waiting to be filled in further.
XSS_PLACEHOLDER_PAYLOADS = [
    "</div><scrIpt>alert(1);</scRipt><div>",
]


def dedupe_preserve_order(items: list[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for item in items:
        if item not in seen:
            seen.add(item)
            out.append(item)
    return out


def filter_and_record(
    idx: ef.TrainingIndex,
    category: str,
    payloads: list[str],
    report: dict,
) -> list[str]:
    kept: list[str] = []
    for p in payloads:
        result = ef.check_candidate(idx, category, p)
        report["candidates_generated"][category] += 1
        if result.kept:
            kept.append(p)
        else:
            report["candidates_discarded"][category] += 1
            report["discard_reasons"][category][result.reason or "unknown"] += 1
            src = result.matched_source or "unknown"
            report["discard_sources"][category][src] += 1
            report["discard_examples"][category].append(
                {"payload": p[:200], "reason": result.reason, "source": src}
            )
    return kept


def build_request_specs(
    rng: random.Random,
    idx: ef.TrainingIndex,
    report: dict,
) -> list[dict]:
    specs: list[dict] = []
    next_id = Counter()

    def add(category: str, method: str, path: str, param: str, payload: str, extra: dict, auth: str):
        idx_n = next_id[category]
        next_id[category] += 1
        specs.append(
            {
                "id": f"{category}_{idx_n}",
                "category": category,
                "method": method,
                "path": path,
                "param": param,
                "payload": payload,
                "extra": extra,
                "auth": auth,
            }
        )

    # --- sqli: GET /posts/search?q= ---
    sql_traffic = sqlmap_extract.extract_all(SQLMAP_OUT_DIR)
    search_candidates = dedupe_preserve_order(sql_traffic["search_q"])
    search_kept = filter_and_record(idx, "sqli", search_candidates, report)
    rng.shuffle(search_kept)
    for p in search_kept[: TARGET_COUNTS["sqli_search"]]:
        add("sqli", "GET", "/posts/search", "q", p, {}, "alice")

    # --- sqli: POST /login (username) ---
    login_candidates = dedupe_preserve_order(sql_traffic["login_username"])
    login_kept = filter_and_record(idx, "sqli", login_candidates, report)
    rng.shuffle(login_kept)
    for p in login_kept[: TARGET_COUNTS["sqli_login"]]:
        add("sqli", "POST", "/login", "username", p, {"password": "x"}, "alice")

    # --- path_traversal: GET /posts/1/attachment?file= ---
    pt_pool = path_traversal_gen.generate(seed=SEED, count=TARGET_COUNTS["path_traversal"] * 2)
    pt_kept = filter_and_record(idx, "path_traversal", pt_pool, report)
    for p in pt_kept[: TARGET_COUNTS["path_traversal"]]:
        add("path_traversal", "GET", "/posts/1/attachment", "file", p, {}, "alice")

    # --- cmdi: POST /admin/ping (host), requires admin session ---
    cmdi_pool = cmdi_gen.generate(seed=SEED, count=TARGET_COUNTS["cmdi"] * 2)
    cmdi_kept = filter_and_record(idx, "cmdi", cmdi_pool, report)
    for p in cmdi_kept[: TARGET_COUNTS["cmdi"]]:
        add("cmdi", "POST", "/admin/ping", "host", p, {}, "admin")

    # --- xss: real OWASP ZAP active-scan export (2026-10-10), n=1 confirmed ---
    # Targets POST /profile (bio) specifically - that's the parameter ZAP
    # actually confirmed exploitable. POST /posts (content/title) tested
    # clean in the same scan; pointing this payload there instead would
    # silently test something other than the confirmed vulnerability.
    xss_kept = filter_and_record(idx, "xss", list(XSS_PLACEHOLDER_PAYLOADS), report)
    for p in xss_kept:
        add("xss_placeholder", "POST", "/profile", "bio", p, {}, "alice")

    return specs


def main() -> None:
    report = {
        "seed": SEED,
        "candidates_generated": Counter(),
        "candidates_discarded": Counter(),
        "discard_reasons": {c: Counter() for c in ("sqli", "path_traversal", "cmdi", "xss")},
        "discard_sources": {c: Counter() for c in ("sqli", "path_traversal", "cmdi", "xss")},
        "discard_examples": {c: [] for c in ("sqli", "path_traversal", "cmdi", "xss")},
    }
    for c in ("sqli", "path_traversal", "cmdi", "xss"):
        report["candidates_generated"].setdefault(c, 0)
        report["candidates_discarded"].setdefault(c, 0)

    print("Building training index (reading sibling repo training/data_clean/*.jsonl, read-only)...")
    idx = ef.build_training_index()
    print(f"  {idx.records_read} training records read from {len(idx.files_read)} files")

    rng = random.Random(SEED)
    specs = build_request_specs(rng, idx, report)

    if OUTPUT_PATH.exists() and not BACKUP_PATH.exists():
        BACKUP_PATH.write_text(OUTPUT_PATH.read_text())
        print(f"Backed up leaked corpus to {BACKUP_PATH}")

    with open(OUTPUT_PATH, "w") as f:
        json.dump(specs, f, indent=2)

    by_category = Counter(s["category"] for s in specs)
    print(f"\nWrote {len(specs)} request specs to {OUTPUT_PATH}")
    for cat, n in sorted(by_category.items()):
        print(f"  {cat}: {n}")

    # Serialize report (Counters -> plain dicts)
    def plainify(obj):
        if isinstance(obj, Counter):
            return dict(obj)
        if isinstance(obj, dict):
            return {k: plainify(v) for k, v in obj.items()}
        return obj

    report_out = plainify(report)
    report_out["training_files_read"] = idx.files_read
    report_out["training_records_read"] = idx.records_read
    report_out["final_corpus_counts"] = dict(by_category)
    report_out["xss_status"] = "REAL - OWASP ZAP active scan via REST API, 2026-10-10. n=1 confirmed-vulnerable parameter (profile.bio); content/title tested clean. See attack-sim/zap-evidence/."

    with open(REPORT_PATH, "w") as f:
        json.dump(report_out, f, indent=2)
    print(f"Wrote exclusion report to {REPORT_PATH}")


if __name__ == "__main__":
    main()
